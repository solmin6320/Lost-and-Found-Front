import { describe, expect, it } from 'vitest'

import { detectPersonalInfo } from './personalInfo'

describe('detectPersonalInfo — 쓰는 칸의 개인정보 모양(SE-3)', () => {
  it.each([
    ['010-1234-5678'],
    ['연락 주세요 010 1234 5678 입니다'],
    ['01012345678'],
    ['010.1234.5678'],
    ['011-123-4567'],
    ['+82 10-1234-5678'],
    ['+821012345678'],
    ['02-123-4567'],
    ['031-1234-5678'],
    ['031)123-4567'],
    ['070-1234-5678'],
    ['보관소 대표번호 1588-1234 로 전화하세요'],
  ])('전화번호 %j 를 알아본다', (text) => {
    expect(detectPersonalInfo(text)).toBe('phone')
  })

  it.each([['900101-1234567'], ['9001011234567'], ['900101 2234567'], ['900101-1******']])(
    '주민등록번호 %j 를 알아본다',
    (text) => {
      expect(detectPersonalInfo(text)).toBe('residentId')
    },
  )

  it.each([['4111 1111 1111 1111'], ['4111-1111-1111-1111'], ['4111111111111111'], ['카드 5555555555554444 분실']])(
    '카드 번호 %j 를 알아본다',
    (text) => {
      expect(detectPersonalInfo(text)).toBe('card')
    },
  )

  // 분실물 글에 흔한 숫자 — 잘못 걸리면 사람들이 그 줄을 읽지 않게 된다
  it.each([
    ['2026-09-24 오후에 잃어버렸어요'],
    ['2026.09.24'],
    ['2026-02-24 14:30쯤'],
    ['2026/03/15'],
    ['146번 버스에 두고 내렸어요'],
    ['7016번 버스 뒷자리'],
    ['사례금 50,000원 드려요'],
    ['1,500,000원짜리 노트북'],
    ['09:30 에서 10:00 사이'],
    ['지하철 2호선 강남역 3번 출구'],
    ['학번 20231234 학생증'],
    ['1995-2000년식'],
    ['송장 1234567890123'],
    ['주문번호 1234567812345678'],
    ['아이폰 15 프로 256GB'],
    ['010 이라고 적힌 스티커'],
    ['우편번호 06236'],
    [''],
  ])('흔한 숫자 %j 는 걸리지 않는다', (text) => {
    expect(detectPersonalInfo(text)).toBeNull()
  })

  it('여럿이 섞이면 가장 민감한 하나만 말한다', () => {
    expect(detectPersonalInfo('010-1234-5678 / 900101-1234567')).toBe('residentId')
    expect(detectPersonalInfo('010-1234-5678 / 4111 1111 1111 1111')).toBe('card')
  })
})
